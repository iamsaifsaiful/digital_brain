String state(AppData d) => [
      for (final x in d.tasks) '${x.id}|${x.title}|${x.due}|${x.span}|${x.done}|${x.reminderId}',
      for (final r in d.reminders) 'R:${r.id}|${r.title}|${r.date}|${r.hour}|${r.enabled}|${r.repeat}',
