import 'package:flutter_test/flutter_test.dart';

import 'walk.dart';

Future<void> run(WidgetTester t, String id, String who, List<String> lines, {String? page}) async {
  final w = await Walk.begin(t, id, who);
  await w.openMic();
  for (final s in lines) {
    await w.say(s);
  }
  if (page != null) {
    await w.say(page);
    await w.shot('page');
  } else {
    await w.shot('chat');
  }
  await w.done();
}

