# Writes the plugin's intent list (tool/wordpress/my-assistant-accounts/nlu-intents.php)
# from the spec, so the server's cloud reading uses exactly the spec's names.
#   python3 tool/nlu/spec/php_intents.py
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(HERE, 'intents.json')))
slots = json.load(open(os.path.join(HERE, 'slots.json')))
out = os.path.join(HERE, '..', '..', 'wordpress', 'my-assistant-accounts', 'nlu-intents.php')


def short(s, n=90):
    s = re.sub(r'\s+', ' ', s).strip()
    s = s.split('। ')[0]
    return (s[:n] + '…') if len(s) > n else s


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


lines = ['<?php', '/** Generated by tool/nlu/spec/php_intents.py from docs/nlu-spec.md — do not edit by hand. */', '',
         "if (!defined('ABSPATH')) {", '    exit;', '}', '', 'const MA_NLU_INTENTS = [']
for x in spec:
    lines.append(f"    {q(x['id'])} => {q(short(x['when']))},")
lines += ['];', '', '/** Intents only the phone may handle (secrets, health, contacts): never resolved in the cloud. */', 'const MA_NLU_PHONE_ONLY = [']
lines.append('    ' + ', '.join(q(x['id']) for x in spec if x.get('phone_only')) + ',')
lines += ['];', '', 'const MA_NLU_SLOTS = [']
lines.append('    ' + ', '.join(q(k) for k in slots) + ',')
lines += ['];', '']
open(out, 'w').write('\n'.join(lines))
print(out, len(spec), 'intents', len(slots), 'slots')
