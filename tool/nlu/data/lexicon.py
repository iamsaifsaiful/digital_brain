def person():
    r = random.random()
    if r < 0.6:
        male = random.random() < 0.6
        n = random.choice(MALE if male else FEMALE)
        if random.random() < 0.15:
            n = f'{n} {random.choice(HONORIFIC_M if male else HONORIFIC_F)}'
        return n
    if r < 0.75:
        return random.choice(FULL_NAMES)
    return random.choice(RELATIONS)


def with_case(name, case):
    """রহিম + কে/এর/কাছে… The ending joins the last word; a name ending in a
    vowel takes the short form."""
    if case == 'plain':
        return name
    if case == 'ke':
        return name + 'কে'
    g = gen(name)
    return {'er': g, 'kache': g + ' কাছে', 'theke': g + ' কাছ থেকে'}[case]


def gen(w):
    """Genitive: মিটিং → মিটিংয়ের, খাওয়া → খাওয়ার, ভাই → ভাইয়ের, নামাজ → নামাজের."""
    if w.endswith('ং') or w[-1] in 'ইউওএ':
        return w + 'য়ের'
    if w[-1] in 'ািীুূেৈোৌ':
        return w + 'র'
    return w + 'ের'


def loc(w):
    """Locative: বিকাশে, ডাচ বাংলায়, নগদে, ব্যাংকে."""
    if w[-1] in 'া':
        return w + 'য়'
    if w[-1] in 'িীুূেৈোৌইউওএ' or w.endswith('ং'):
        return w + 'তে'
    return w + 'ে'


